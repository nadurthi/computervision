"""Write SUMMARY.md: test function, every sample point used, and the comparison results."""
import os, pickle, numpy as np, l1fit
HERE = os.path.dirname(os.path.abspath(__file__))
S = pickle.load(open(os.path.join(HERE, "points.pkl"), "rb"))
logf = l1fit.logf_tbanana
g = np.linspace(-1, 1, 161); GX, GY = np.meshgrid(g, g); G = np.c_[GX.ravel(), GY.ravel()]
ins = np.all(np.abs(G) <= 0.85, axis=1); FT = np.exp(logf(G))
rm = lambda F: 100*np.sqrt(np.mean((F[ins]-FT[ins])**2))/FT.max()

L = []
L += ["# Summary: L1 polynomial fit at sparse points — uniform vs Gauss–Hermite vs CUT-8", "",
"Generated by `make_summary.py` from `points.pkl` and `l1fit.py`.", "",
"## 1. Function being fit", "",
"Default test surface `tbanana` (heavy-tailed, Student-t ν = 4 banana) on the box [−1, 1]²:", "",
"```", "log f(x, y) = −(ν+1)/2 · log(1 + q/ν) + 1.2,     ν = 4",
"q          = (x / 0.35)² + ((y − 1.6 x² + 0.35) / 0.22)²", "```", "",
f"Peak at (0, −0.35), f_max = {FT.max():.4f}. Its log is not a polynomial, so no degree fits it exactly.", "",
"Model fitted: f(x, y) ≈ exp(p(x, y)), with p = Σ λᵢ xᵃ yᵇ over all monomials with a + b ≤ 6 (28 coefficients).", "",
"Other surfaces in `l1fit.py`:", "",
"- `banana`: log f = −½[(x/0.35)² + ((y − 1.6x² + 0.35)/0.22)²] + 1.2. Its log is an exact degree-4 polynomial, so it is an easy case.",
"- `mixture`: a 3-component Gaussian mixture. Means (−0.30, −0.15), (0.25, 0.20), (0.05, −0.45); weights 0.45, 0.35, 0.20. `smooth` scales every covariance.", "",
"## 2. Sample points", "",
"Gauss–Hermite and CUT-8 are defined for a standard normal N(0, I), and the uniform grid on [−1, 1]² (\"raw\"). Each set is then scaled by one factor so that max|coordinate| = 0.85 (\"fit\"). "
"The fit coordinates are where f is evaluated. The weights are quadrature weights (N(0, I) for Gauss–Hermite and CUT-8, equal for the uniform grid). The fit itself does not use them.", ""]
for k, s in S.items():
    X, W, Xs = s["raw"], s["w"], s["X"]
    sc = Xs[0, 0] / X[0, 0] if X[0, 0] != 0 else Xs[np.nonzero(X[:, 0])[0][0], 0] / X[np.nonzero(X[:, 0])[0][0], 0]
    L += [f"### {s['label']} — {len(X)} points (scale factor {sc:.5f})", "",
          "| # | x raw | y raw | weight | x fit | y fit | f(x fit, y fit) |", "|---|---|---|---|---|---|---|"]
    for i, (p, w, q) in enumerate(zip(X, W, Xs), 1):
        L.append(f"| {i} | {p[0]:.5f} | {p[1]:.5f} | {w:.6f} | {q[0]:.5f} | {q[1]:.5f} | {np.exp(logf(q[None]))[0]:.5f} |")
    L.append("")
L += ["Guard points: a 23 × 23 grid on [−2.2, 2.2]² with the points inside [−1.5, 1.5]² removed (304 points). "
      "Constraint at each: p(g) ≤ log N(g; 0, I).", ""]

L += ["## 3. Fitting method", "",
"One linear program, solved with `scipy.optimize.linprog` (HiGHS):", "", "```",
"min   C/n · ‖λ‖₁ + 10 · norm_largest(t, k)          n = 28, k = floor(0.75 n) = 21 (capped at #equalities)",
"s.t.  A_eq λ   = log f(x_j) + t                    samples with log f ≥ −9",
"      A_ineq λ ≤ −9                                samples with log f < −9",
"      A_out λ  ≤ log N(g; 0, I)                    guard points", "```", "",
"C is swept over {0.01, 0.1, 25, 100, 250, 300, 500, 800, 1200, 1900, 2500, 3500, 5000, 7500, 10000}. "
"The sweep stops at the first C where the residual at the highest sample reaches 0.01 % of its value, and keeps the previous solution. "
"If every C fails that test, the first solution is kept. This is the rule from the MATLAB original.", ""]

L += ["## 4. Comparison (degree 6)", "",
"Error = RMSE(f̂ − f) / max f, on a 161 × 161 grid restricted to |x|, |y| ≤ 0.85 (the region the samples cover).", "",
"| Point set | Points | C chosen | Nonzero λ | Rank of A | L1 LP error | Least-squares error |", "|---|---|---|---|---|---|---|"]
exps = l1fit.basis_exponents(2, 6)
for k, s in S.items():
    f = l1fit.fit_l1(s["X"], logf, 6)
    A = l1fit.design(s["X"], exps); rk = np.linalg.matrix_rank(A, tol=1e-10*np.linalg.norm(A, 2))
    ls = np.linalg.lstsq(A, logf(s["X"]), rcond=None)[0]
    with np.errstate(over="ignore"):
        e_ls = rm(np.exp(l1fit.design(G, exps) @ ls))
    L.append(f"| {s['label']} | {len(s['X'])} | {f['C']} | {int(np.sum(np.abs(f['lam'])>1e-6))} / 28 | {rk} | {rm(l1fit.evaluate(f, G)):.1f} % | {e_ls:.1f} % |")
L += ["", "Error vs degree (L1 LP):", "", "| Degree | " + " | ".join(str(d) for d in range(2, 11)) + " |", "|---" * 10 + "|"]
for k, s in S.items():
    L.append(f"| {s['label']} | " + " | ".join(f"{rm(l1fit.evaluate(l1fit.fit_l1(s['X'], logf, d), G)):.1f}" for d in range(2, 11)) + " |")
L += ["", "## 5. Summary", "",
"- **CUT-8 is about 3× more accurate with 4 fewer points** at degree 6 (4.1 % vs 14.9 % uniform and 13.9 % Gauss–Hermite). "
"At each method's best degree it is still about 2× better (3.9 % vs 7.5–7.8 %).",
"- **Why the grids fail:** a 5-node-per-axis tensor grid has the degree-5 node polynomial ω(x) = Πₖ(x − xₖ). ω(x), xω(x), yω(x) and the same three in y "
"vanish at all 25 nodes, so the 25 × 28 design matrix has rank 22. No degree-6 polynomial fits all 25 samples. The L1-type residual then satisfies 23 equations exactly "
"and puts the misfit on the peak sample (−1.23 log units on the uniform grid, which leaves the fitted peak at about 29 % of the true one).",
"- **Why CUT-8 works:** it is not a tensor product. Its 21 × 28 design matrix has full row rank (21, condition number about 660), so every sample is fitted exactly "
"and the L1 term only chooses among exact interpolants.",
"- **Quadrature exactness is not the mechanism.** Gauss–Hermite 5×5 is exact for xⁱyʲ with i, j ≤ 9, and CUT-8 is exact for i + j ≤ 9. Both are exact for the whole degree-6 basis.",
"- **The grid failure is avoidable.** Use degree < nodes per axis (≤ 4 here), least squares instead of the L1 residual (which halves the grid error), or a non-tensor design.",
"- **Caveats:** the surface was chosen to show the effect. On a 3-mode Gaussian mixture all three sets reach only 12–14 %, with CUT-8 slightly ahead. On very smooth, near-Gaussian "
"surfaces the 25-point grids are slightly better at high degree. The shared max|x| = 0.85 scaling also puts more CUT-8 points near the center (5 within r < 0.3, against 1 for each grid).", ""]
open(os.path.join(HERE, "SUMMARY.md"), "w").write("\n".join(L))
print("wrote SUMMARY.md")
